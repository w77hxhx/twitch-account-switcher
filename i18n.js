function getTwitchCurrentLocale() {
  const htmlLang = (document.documentElement.lang || document.documentElement.getAttribute("lang") || "").toLowerCase();
  if (htmlLang) {
    if (htmlLang.startsWith("zh-tw") || htmlLang.startsWith("zh-hk")) return "zh-TW";
    if (htmlLang.startsWith("zh")) return "zh";
    for (const code of Object.keys(TAS_I18N)) {
      if (htmlLang.startsWith(code)) return code;
    }
  }

  const nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
  if (nav.startsWith("zh-tw") || nav.startsWith("zh-hk")) return "zh-TW";
  if (nav.startsWith("zh")) return "zh";
  for (const code of Object.keys(TAS_I18N)) {
    if (nav.startsWith(code)) return code;
  }

  return "en";
}

function t(key) {
  const lang = getTwitchCurrentLocale();
  const dict = TAS_I18N[lang] || TAS_I18N.en;
  return dict[key] || TAS_I18N.en[key] || key;
}

if (typeof window !== "undefined") {
  window.TAS_I18N = TAS_I18N;
  window.tasT = t;
  window.tasGetLocale = getTwitchCurrentLocale;
}
